#!/usr/bin/env python3
"""Generate debug.lua -- the built script plus both diagnostics.

The diagnostics live here rather than in src/global.lua so the shipped mod
stays lean. Focus the generated debug.lua in VS Code and press
Ctrl+Shift+E: it prints every object Global can see, then per card whether it
is labeled and whether renderCard succeeded.

Run: python tools/debug.py
"""
import io, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                       # tts_envs/
WORKSPACE = os.path.dirname(ROOT)
BUILT = os.path.join(WORKSPACE, ".tts", "objects", "Global.lua")
OUT = os.path.join(ROOT, "debug.lua")   # beside master_reload.lua: both are
                                        # Execute Code targets, not helpers

LUA = '''-- Diagnostic: what does Global actually see on the table?
function debugTable()
  local n = 0
  for _, obj in ipairs(getAllObjects()) do
    n = n + 1
    print(string.format("%s | tag=%s type=%s name=%q gm=%q memo=%q",
      obj.getGUID(), tostring(obj.tag), tostring(obj.type),
      tostring(obj.getName()), tostring(obj.getGMNotes()), tostring(obj.memo)))
  end
  print("total objects: "..n.."  EVENT_DATA loaded: "..tostring(EVENT_DATA ~= nil))
end

-- Diagnostic: is a blank card a labeling problem or a rendering problem?
function debugUI()
  for _, obj in ipairs(getAllObjects()) do
    local tag = obj.tag or obj.type
    if tag == "Card" then
      print(string.format("%s gm=%q memo=%q",
        obj.getGUID(), tostring(obj.getGMNotes()), tostring(obj.memo)))
      print("rendered: "..tostring(renderCard(obj)))
    end
  end
end
'''

if not os.path.exists(BUILT):
  raise SystemExit("missing %s -- run master_sync.cmd first" % BUILT)

built = io.open(BUILT, encoding="utf-8").read()
io.open(OUT, "w", encoding="utf-8", newline="\n").write(
  "-- GENERATED by tools/debug.py -- do not edit\n"
  "-- Focus this file in VS Code and press Ctrl+Shift+E to run it in TTS.\n\n"
  + built + "\n\n" + LUA +
  '\nprint("--- debugTable ---")\ndebugTable()\n'
  'print("--- debugUI ---")\ndebugUI()\n')
print("wrote %s" % os.path.relpath(OUT, ROOT))
