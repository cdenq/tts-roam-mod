#!/usr/bin/env python3
"""Convert cards.xlsx origins into the ORIGIN_DATA table in the Global script.

An origin is a card a player picks at the start to specialise their character.
It renders like an event card -- id in GMNotes, Global draws it -- but it has no
branching: a single button spawns everything the origin grants, and the card is
NOT consumed, so it stays on the table as a record of the choice.

Origin ids must not collide with event node ids, because renderCard resolves a
card's GMNotes against both tables. Event ids are EV-prefixed; origins use O.

Run: python tools/sync/sync_origins_data.py
"""
import os, sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(1, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # tools/: datasets, spawn_cells, lua_inline
from spawn_cells import SPAWN_CATEGORIES, read_spawn, referenced_names
from datasets import (ROOT, CARDS, ORIGINS_SHEET,
                      intro_rows, read_rows, item_names, token_names,
                      event_node_ids,
                      template_cell, template_collisions, generic_ids)

OUT = os.path.join(ROOT, "generated", "origin_data.lua")
WORKSPACE = os.path.dirname(ROOT)
GLOBAL = os.path.join(WORKSPACE, ".tts", "objects", "Global.lua")

BEGIN = "--[[ BEGIN GENERATED ORIGIN DATA -- do not edit ]]"
END = "--[[ END GENERATED ORIGIN DATA ]]"

warnings_out = []


def warn(msg):
  warnings_out.append(msg)


def lua_str(s):
  s = (s or "").replace("\\", "\\\\").replace('"', '\\"')
  s = s.replace("\r", "").replace("\n", "\\n")
  return '"' + s + '"'


def main():
  rows = read_rows(CARDS, ORIGINS_SHEET, "origin_id")
  if not rows:
    sys.exit("no origins in " + CARDS)

  # Event ids live in the same GMNotes namespace, so a collision would make
  # a card resolve to the wrong table.
  node_ids = set()
  if os.path.exists(CARDS):
    node_ids = event_node_ids()

  known = item_names()
  meeples = token_names()
  origins = []
  seen = {}
  for r in rows:
    where = r["_where"]
    oid = (r.get("origin_id") or "").strip()
    name = (r.get("name") or "").strip()

    if not name:
      sys.exit("%s: %s has no name" % (where, oid))
    if oid in seen:
      sys.exit("duplicate origin_id %r (%s and %s)" % (oid, seen[oid], where))
    seen[oid] = where
    if oid in node_ids:
      sys.exit("%s: origin_id %r is also an event node_id -- a card's GMNotes "
               "would resolve to the wrong table" % (where, oid))

    spawn = read_spawn(r)
    if not spawn:
      warn("%s: %s grants nothing -- its button would do nothing"
           % (where, name))

    for ref in referenced_names(r, keys=("items",)):
      if ref not in known:
        warn("%s: %s grants %r, which is not in tiles.xlsx -- the spawn will "
             "fail in game" % (where, name, ref))
    for ref in referenced_names(r, keys=("meeple",)):
      if ref not in meeples:
        warn("%s: %s grants meeple %r, which is not in tokens.xlsx -- the "
             "spawn will fail in game" % (where, name, ref))

    # Optional art. TTS fetches a decal url itself, so only a web url works.
    image = (r.get("card_image") or "").strip()
    if image and not image.lower().startswith(("http://", "https://")):
      warn("%s: %s card_image %r is not an http(s) url -- the card will "
           "show no image" % (where, name, image))
      image = ""

    origins.append({
      "id": oid,
      "name": name,
      "image": image,
      "template": template_cell(r, where),
      "effect": (r.get("effect") or "").strip(),
      "flavor": (r.get("flavor") or "").strip(),
      "spawn": spawn,
    })

  #[[ Every card lands in the one Card Importer bag carrying its id in
  # GMNotes, so no template -- origin or event -- may share an id.
  templates = [o["template"] for o in origins]
  if os.path.exists(CARDS):
    templates += [r.get("template", "") for r in intro_rows()]
  template_collisions(templates, (node_ids | set(seen)) - generic_ids(), "a card id")

  # ---- build the Lua ------------------------------------------------------
  L = ["-- GENERATED by tools/sync/sync_origins_data.py -- do not edit by hand",
       "--",
       "-- Keyed by origin id, which a card carries in its GMNotes.",
       "ORIGIN_DATA = {"]
  for o in origins:
    L.append("  [%s] = {" % lua_str(o["id"]))
    L.append("    name = %s," % lua_str(o["name"]))
    L.append("    template = %s," % lua_str(o["template"]))
    if o["image"]:
      L.append("    image = %s," % lua_str(o["image"]))
    L.append("    effect = %s," % lua_str(o["effect"]))
    L.append("    flavor = %s," % lua_str(o["flavor"]))
    sp = o["spawn"]
    if sp:
      L.append("    spawn = {")
      for cat in SPAWN_CATEGORIES:
        slots = sp.get(cat["key"])
        if not slots:
          continue
        inner = ", ".join("{%s}" % ", ".join(lua_str(x) for x in slot)
                          for slot in slots)
        L.append("      %s = {%s}," % (cat["key"], inner))
      if "gold" in sp:
        L.append("      gold = {%d, %d}," % sp["gold"])
      L.append("    },")
    L.append("  },")
  L.append("}")
  L.append("")
  L.append("-- Origin ids in sheet order, for anything that needs the full list.")
  L.append("ORIGIN_ORDER = {%s}"
           % ", ".join(lua_str(o["id"]) for o in origins))
  data_lua = "\n".join(L)

  os.makedirs(os.path.dirname(OUT), exist_ok=True)
  with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(data_lua + "\n")

  if not os.path.exists(GLOBAL):
    sys.exit("missing %s -- run tools/sync/sync_events_data.py first" % GLOBAL)
  with open(GLOBAL, encoding="utf-8") as f:
    script = f.read()
  #[[ This appends to a Global that sync_events_data.py has just rebuilt from
  # src/global.lua. Running against a stale one silently produces a file with
  # the data but none of the functions that use it.
  if "function renderCard" not in script:
    sys.exit("%s was not built from src/global.lua -- run "
             "tools/sync/sync_events_data.py first" % os.path.relpath(GLOBAL, WORKSPACE))
  block = BEGIN + "\n" + data_lua + "\n" + END
  if BEGIN in script and END in script:
    script = script.split(BEGIN)[0] + block + script.split(END, 1)[1]
  else:
    script = script.rstrip() + "\n\n" + block + "\n"
  with open(GLOBAL, "w", encoding="utf-8", newline="\n") as f:
    f.write(script)

  for w in warnings_out:
    print("  warning: " + w)
  print("wrote %s (%d origin%s)"
        % (os.path.relpath(OUT, ROOT), len(origins),
           "" if len(origins) == 1 else "s"))
  print("wrote %s (%d bytes)"
        % (os.path.relpath(GLOBAL, WORKSPACE), len(script)))


main()
