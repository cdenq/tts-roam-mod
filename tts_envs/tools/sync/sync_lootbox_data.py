#!/usr/bin/env python3
"""Convert tiles.xlsx!lootbox_table into the LOOTBOX table in Global.

A lootbox is an item that is CONSUMED to spawn a table of other items. The item
itself lives on an item sheet of tiles.xlsx as `type=consumable,
subtype=lootbox`; what it contains lives on the lootbox_table sheet, one row
per box.

The table goes into GLOBAL rather than onto the importer bag, because Global is
what draws the Open button and runs the spawn. It is keyed by item NAME, since
that is what Global can read off an object without any lookup -- the same key
findInBag already uses.

Only lootboxes end up in the table, so it stays small.

Run: python tools/sync/sync_lootbox_data.py
"""
import os, sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(1, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # tools/: datasets, spawn_cells, lua_inline
from spawn_cells import (SPAWN_CATEGORIES, read_spawn, referenced_names,
                         spawn_columns)
from datasets import ROOT, TILES, ITEM_SHEETS, LOOTBOX_SHEET, load, read_rows

OUT = os.path.join(ROOT, "generated", "lootbox_data.lua")
WORKSPACE = os.path.dirname(ROOT)
GLOBAL = os.path.join(WORKSPACE, ".tts", "objects", "Global.lua")

BEGIN = "--[[ BEGIN GENERATED LOOTBOX DATA -- do not edit ]]"
END = "--[[ END GENERATED LOOTBOX DATA ]]"

warnings_out = []


def warn(msg):
  warnings_out.append(msg)


def lua_str(s):
  s = (s or "").replace("\\", "\\\\").replace('"', '\\"')
  s = s.replace("\r", "").replace("\n", "\\n")
  return '"' + s + '"'


def main():
  wb = load(TILES)
  boxes = read_rows(TILES, LOOTBOX_SHEET, "item_id", wb)
  items = read_rows(TILES, ITEM_SHEETS, "item_id", wb)

  by_id = {}
  by_name = set()
  marked = {}            # item_id -> name, for every subtype=lootbox item
  for it in items:
    by_id[it["item_id"]] = it
    if it.get("name"):
      by_name.add(it["name"])
    if it.get("subtype", "").lower() == "lootbox":
      marked[it["item_id"]] = it.get("name", "")

  table = []
  seen = set()
  for b in boxes:
    where = b["_where"]
    iid = b["item_id"]

    item = by_id.get(iid)
    if item is None:
      sys.exit("%s: item_id %r is not in tiles.xlsx" % (where, iid))
    name = item.get("name", "")
    if not name:
      sys.exit("%s: item %r has no name" % (where, iid))
    if item.get("subtype", "").lower() != "lootbox":
      sys.exit("%s: %s is subtype %r, not 'lootbox' -- an item needs that "
               "subtype to be openable" % (where, name, item.get("subtype")))
    if name in seen:
      sys.exit("%s: two lootbox rows for %r" % (where, name))
    seen.add(name)

    # The sheet's own `name` column is for reading while authoring; the item
    # sheet is authoritative, so flag a mismatch rather than trusting either.
    if b.get("name") and b["name"] != name:
      warn("%s: name column says %r but the item sheet says %r -- using that"
           % (where, b["name"], name))

    spawn = read_spawn(b)
    if not spawn:
      warn("%s: %s has no spawn cells filled in -- opening it gives nothing"
           % (where, name))

    for ref in referenced_names(b, keys=("items",)):
      if ref not in by_name:
        warn("%s: %s drops %r, which is not in tiles.xlsx -- the spawn will "
             "fail in game" % (where, name, ref))

    table.append((name, spawn))

  for iid, name in sorted(marked.items()):
    if name not in seen:
      warn("%s is subtype=lootbox but has no row on lootbox_table -- opening "
           "it would give nothing" % (name or iid))

  # ---- build the Lua ------------------------------------------------------
  L = ["-- GENERATED by tools/sync/sync_lootbox_data.py -- do not edit by hand",
       "--",
       "-- Keyed by item NAME, which is what Global can read off an object.",
       "LOOTBOX = {"]
  for name, spawn in table:
    L.append("  [%s] = {" % lua_str(name))
    for cat in SPAWN_CATEGORIES:
      slots = spawn.get(cat["key"])
      if not slots:
        continue
      inner = ", ".join("{%s}" % ", ".join(lua_str(x) for x in slot)
                        for slot in slots)
      L.append("    %s = {%s}," % (cat["key"], inner))
    if "gold" in spawn:
      L.append("    gold = {%d, %d}," % spawn["gold"])
    L.append("  },")
  L.append("}")
  data_lua = "\n".join(L)

  os.makedirs(os.path.dirname(OUT), exist_ok=True)
  with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(data_lua + "\n")

  if not os.path.exists(GLOBAL):
    sys.exit("missing %s -- run tools/sync/sync_events_data.py first" % GLOBAL)
  with open(GLOBAL, encoding="utf-8") as f:
    script = f.read()

  #[[ This script APPENDS to a Global that sync_events_data.py has just rebuilt
  # from src/global.lua. Running it against a stale or already-appended Global
  # silently produces a file with the lootbox block but none of the functions
  # that use it. Checking for rollSpawn catches that.
  if "function rollSpawn" not in script:
    sys.exit("%s has no rollSpawn() -- it was not built from src/global.lua. "
             "Run tools/sync/sync_events_data.py first; master_sync.cmd does this in "
             "the right order." % os.path.relpath(GLOBAL, WORKSPACE))
  block = BEGIN + "\n" + data_lua + "\n" + END
  if BEGIN in script and END in script:
    script = script.split(BEGIN)[0] + block + script.split(END, 1)[1]
  else:
    script = script.rstrip() + "\n\n" + block + "\n"
  with open(GLOBAL, "w", encoding="utf-8", newline="\n") as f:
    f.write(script)

  for w in warnings_out:
    print("  warning: " + w)
  print("wrote %s (%d lootbox%s)"
        % (os.path.relpath(OUT, ROOT), len(table),
           "" if len(table) == 1 else "es"))
  print("wrote %s (%d bytes)" % (os.path.relpath(GLOBAL, WORKSPACE),
                                 len(script)))


main()
