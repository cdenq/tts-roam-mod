#!/usr/bin/env python3
"""Convert tokens.xlsx!landmark_table into the LANDMARK_DATA table in Global.

A landmark's GMNotes (tokens.xlsx landmarks sheet) is its KIND -- "cave",
"fishing_node" -- shared by every landmark that behaves alike. landmark_table
has one row per kind, saying what Global attaches to it:

  gmnotes   the kind; lowercase snake_case so it can never be mistaken for an
            event (EV..) or origin (O..) card id, which also key on GMNotes
  actions   "inspect|enter": buttons, in order. Each must be a key of
            LANDMARK_ACTIONS in src/global.lua -- that is where an action's
            label and click function live

The landmark's own data (name, faction, tier, image) stays on tokens.xlsx;
only behaviour lives here, so nothing is written twice. A kind reaches an
object from its tokens.xlsx gmnotes, or from a stamp Explore or Render puts on
what it spawns (biome_render <spawncol>_gmnotes; Explore stamps memo only);
all are cross-checked.

Run: python tools/sync/sync_landmark_data.py
"""
import os, re, sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(1, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # tools/: datasets, spawn_cells, lua_inline
from datasets import ROOT, MAPTILES, TOKENS, LANDMARK_SHEET, LANDMARK_TABLE_SHEET, load, read_rows

SHEET = LANDMARK_TABLE_SHEET
SRC = os.path.join(ROOT, "src", "global.lua")
OUT = os.path.join(ROOT, "generated", "landmark_data.lua")
WORKSPACE = os.path.dirname(ROOT)
GLOBAL = os.path.join(WORKSPACE, ".tts", "objects", "Global.lua")

BEGIN = "--[[ BEGIN GENERATED LANDMARK DATA -- do not edit ]]"
END = "--[[ END GENERATED LANDMARK DATA ]]"
KIND = re.compile(r"^[a-z][a-z0-9_]*$")

warnings_out = []


def warn(msg):
  warnings_out.append(msg)


def lua_str(s):
  s = (s or "").replace("\\", "\\\\").replace('"', '\\"')
  return '"' + s + '"'


def known_actions():
  """The keys of LANDMARK_ACTIONS in src/global.lua: the only actions a row may name."""
  src = open(SRC, encoding="utf-8").read()
  m = re.search(r"^LANDMARK_ACTIONS = \{\n(.*?)^\}", src, re.M | re.S)
  if m is None:
    sys.exit("%s has no LANDMARK_ACTIONS table" % os.path.relpath(SRC, ROOT))
  return set(re.findall(r"^  (\w+) = \{", m.group(1), re.M))


def main():
  wb = load(MAPTILES)
  tokens = load(TOKENS)
  if SHEET not in tokens.sheetnames:
    sys.exit("tokens.xlsx has no %r sheet" % SHEET)
  actions = known_actions()

  #[[ Which kinds landmarks can carry, for the unused/unknown checks. Two
  # sources: the landmark's own gmnotes (tokens.xlsx), and the gmnotes Render
  # (biome_render) stamps on what it spawns -- a stamp wins in game. Explore
  # never stamps GMNotes, only memo.
  used = {}
  for r in read_rows(TOKENS, LANDMARK_SHEET, "name", tokens):
    gm = (r.get("gmnotes") or "").strip()
    if gm:
      used.setdefault(gm, []).append(r["name"])
  # Render stamps: biome_render <spawncol>_gmnotes (spawn_cells.read_stamps).
  for r in read_rows(MAPTILES, "biome_render", "gmnotes", wb):
    for col, value in r.items():
      gm = (value or "").strip() if col.endswith("_gmnotes") else ""
      if gm:
        used.setdefault(gm, []).append("Render %s %s" % (r["gmnotes"], col))

  table = []
  for r in read_rows(TOKENS, SHEET, "gmnotes", tokens):
    where, kind = r["_where"], r["gmnotes"].strip()
    if not KIND.match(kind):
      sys.exit("%s: gmnotes %r -- want lowercase snake_case (cave, fishing_node)"
               % (where, kind))
    if any(k == kind for k, _ in table):
      sys.exit("%s: kind %r is listed twice" % (where, kind))
    picked = [a.strip() for a in (r.get("actions") or "").split("|") if a.strip()]
    for a in picked:
      if a not in actions:
        sys.exit("%s: action %r is not in LANDMARK_ACTIONS (src/global.lua); known: %s"
                 % (where, a, ", ".join(sorted(actions))))
    if kind not in used:
      warn("%s: no landmark has gmnotes %r -- the row does nothing yet" % (where, kind))
    table.append((kind, picked))

  kinds = {k for k, _ in table}
  for gm, names in sorted(used.items()):
    if gm not in kinds:
      warn("%s stamp%s gmnotes %r, which has no %s row -- no buttons"
           % (", ".join(names), "s" if len(names) == 1 else "", gm, SHEET))

  L = ["-- GENERATED by tools/sync/sync_landmark_data.py -- do not edit by hand",
       "--",
       "-- Keyed by landmark KIND (its GMNotes).",
       "LANDMARK_DATA = {"]
  for kind, picked in table:
    L.append("  [%s] = {actions = {%s}}," % (lua_str(kind), ", ".join(lua_str(a) for a in picked)))
  L.append("}")
  data_lua = "\n".join(L)

  os.makedirs(os.path.dirname(OUT), exist_ok=True)
  with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(data_lua + "\n")

  if not os.path.exists(GLOBAL):
    sys.exit("missing %s -- run tools/sync/sync_events_data.py first" % GLOBAL)
  with open(GLOBAL, encoding="utf-8") as f:
    script = f.read()
  # Appends to a Global that sync_events_data.py has just rebuilt; a stale one
  # would get the data without the function that reads it.
  if "function renderLandmark" not in script:
    sys.exit("%s has no renderLandmark() -- it was not built from src/global.lua. "
             "Run master_sync.cmd." % os.path.relpath(GLOBAL, WORKSPACE))
  block = BEGIN + "\n" + data_lua + "\n" + END
  if BEGIN in script and END in script:
    script = script.split(BEGIN)[0] + block + script.split(END, 1)[1]
  else:
    script = script.rstrip() + "\n\n" + block + "\n"
  with open(GLOBAL, "w", encoding="utf-8", newline="\n") as f:
    f.write(script)

  for w in warnings_out:
    print("  warning: " + w)
  print("wrote %s (%d landmark kind%s)" % (os.path.relpath(OUT, ROOT), len(table),
                                         "" if len(table) == 1 else "s"))


main()
